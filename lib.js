// Что считать одним и тем же адресом. Здесь одна функция на всё расширение:
// значок, попап и подсветка на странице спрашивают ключ только у неё, иначе
// три места разъедутся и «дубль» будет означать три разные вещи.

export const ПО_УМОЛЧАНИЮ = {
  тикеты: true,          // /issues/12345 - один тикет, что бы ни висело в хвосте
  безЯкоря: true,        // #note-7 из письма не делает ссылку другой
  безWww: true,
  мусор: ["utm_source", "utm_medium", "utm_campaign", "utm_term", "utm_content",
          "fbclid", "gclid", "yclid", "ref", "tab", "t"],
  подсветка: false,      // помечать на странице ссылки, уже открытые во вкладках
  хостПодсветки: "",     // например redmine.payneteasy.com
  перехват: false,       // не давать открыть второй раз: увести на старую вкладку
  предупреждать: true,   // сказать, если закладку на этот тикет уже сохраняли
  толькоТикеты: true,    // «сложить в папку» берёт тикеты, а не все вкладки
};

// Папка-карантин, куда уезжают лишние закладки. При следующем поиске в неё не
// заходим: иначе перенесённое находится снова и окно врёт, что дубли остались.
export const КАРАНТИН = /^Дубли(\s|$)/;

export async function настройки() {
  const х = await chrome.storage.sync.get("настройки");
  return { ...ПО_УМОЛЧАНИЮ, ...(х.настройки || {}) };
}

export async function сохранить(н) {
  await chrome.storage.sync.set({ настройки: н });
}

/** Ключ адреса. null - адрес, который не сравниваем (chrome://, file:// и прочее). */
export function ключ(адрес, н) {
  let u;
  try {
    u = new URL(адрес);
  } catch {
    return null;
  }
  if (u.protocol !== "http:" && u.protocol !== "https:") return null;

  // host, а не hostname: localhost:3000 и localhost:8080 - разные приложения.
  let хост = u.host.toLowerCase();
  if (н.безWww) хост = хост.replace(/^www\./, "");

  // Тикет узнаём по номеру. Ровно ради этого всё и затевалось: один тикет
  // приходит как /issues/12345, /issues/12345#note-7 и /issues/12345?tab=history.
  // Путь ДО /issues входит в ключ: у Redmine он пустой, а у GitHub и GitLab
  // это репозиторий - задача 5 в двух репозиториях не одна и та же.
  if (н.тикеты) {
    const m = u.pathname.match(/^(.*?)\/issues\/(\d+)(?=[/.]|$)/);
    // «/-» GitLab добавил в адреса позже: /g/p/issues/9 и /g/p/-/issues/9 -
    // одна задача, и старая закладка должна узнаваться.
    if (m) return `${хост}${m[1].replace(/\/-$/, "")} | тикет ${m[2]}`;
  }

  const путь = u.pathname.replace(/\/+$/, "") || "/";
  const пары = [...u.searchParams.entries()]
    .filter(([k]) => !н.мусор.includes(k))
    .sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0))
    .map(([k, v]) => `${k}=${v}`);
  const хвост = пары.length ? "?" + пары.join("&") : "";
  // Якорь бывает двух родов. #note-7 или #section - место на той же странице,
  // адрес он не меняет. А #inbox/письмо, #/маршрут или #12345 и #-100123 в
  // Telegram - адрес внутри приложения: склеить их значит закрыть другое
  // письмо или чат. Выделение текста (#:~:text=...) ставит сам Chrome, оно
  // страницу тоже не меняет.
  const хеш = u.hash.replace(/:~:.*$/, "").replace(/^#$/, "");
  const маршрут = /[/!=@]/.test(хеш) || /^#-?\d+$/.test(хеш);
  const якорь = н.безЯкоря && !маршрут ? "" : хеш;
  return `${хост}${путь}${хвост}${якорь}`;
}

/** Номер тикета из ключа или null. */
export function номерТикета(к) {
  const m = /тикет (\d+)$/.exec(к || "");
  return m ? m[1] : null;
}

/**
 * Заголовок группы для человека. «redmine.pne.com | тикет 12345» ни о чём не
 * говорит, когда таких групп десять - нужны номер и тема.
 */
export function заголовок(г) {
  const номер = номерТикета(г.ключ);
  if (!номер) return г.ключ;
  const сырой = г.список.find((э) => э.title)?.title || "";
  const тема = сырой
    .replace(/\s*[-–—|]\s*Redmine\s*$/i, "")
    .replace(/^\s*(Задача|Bug|Ошибка|Feature)?\s*#?\d+\s*[:.]?\s*/i, "")
    .trim();
  return тема ? `#${номер} · ${тема}` : `Тикет ${номер}`;
}

/** Группы по два и больше. Внутри группы порядок исходный: первым тот, что оставим. */
export function группы(элементы, н) {
  const карта = new Map();
  for (const э of элементы) {
    // pendingUrl - вкладка, которая ещё грузится. Открыв десяток тикетов разом,
    // Антон увидел бы «дублей нет»: url у них появляется не сразу.
    const к = ключ(э.url || э.pendingUrl || "", н);
    if (!к) continue;
    if (!карта.has(к)) карта.set(к, []);
    карта.get(к).push(э);
  }
  const итог = [];
  for (const [к, список] of карта) {
    if (список.length > 1) итог.push({ ключ: к, список });
  }
  итог.sort((a, b) => b.список.length - a.список.length);
  return итог;
}

/** Сколько всего лишних: в каждой группе одно оставляем. */
export function лишних(гр) {
  return гр.reduce((с, г) => с + г.список.length - 1, 0);
}

/**
 * Группы вкладок с уже расставленным приоритетом: кого оставляем.
 * Закреплённая важнее активной, активная важнее случайной - иначе схлопывание
 * убивает закреплённую вкладку или уводит фокус на чужое окно.
 */
export function группыВкладок(вкладки, н) {
  const гр = группы(вкладки, н);
  for (const г of гр) {
    г.список = [...г.список].sort(
      (a, b) => (b.pinned ? 1 : 0) - (a.pinned ? 1 : 0) ||
                (b.active ? 1 : 0) - (a.active ? 1 : 0));
  }
  return гр;
}

/**
 * Группы закладок с приоритетом: оставляем ту, что лежит выше по дереву, а при
 * равной глубине - заведённую раньше. Без этого выживала случайная копия:
 * порядок обхода зависел от того, в каком порядке созданы подпапки.
 */
export function группыЗакладок(закладки, н) {
  const гр = группы(закладки, н);
  for (const г of гр) {
    г.список = [...г.список].sort(
      (a, b) => (a.глубина ?? 0) - (b.глубина ?? 0) ||
                (a.dateAdded ?? 0) - (b.dateAdded ?? 0));
  }
  return гр;
}

/** Кого реально закроем. Закреплённые не трогаем никогда. */
export function лишниеВкладки(гр) {
  return гр.flatMap((г) => г.список.slice(1).filter((в) => !в.pinned));
}
