// Правило дубля без браузера: ключ адреса из lib.js на крайних случаях.
//
//     node tests/lib-keys.mjs
//
// Провал - любое из:
//   1. тикеты Redmine с хвостом (#note, ?tab, /edit) получают разные ключи;
//   2. задачи GitHub или GitLab с одним номером в РАЗНЫХ репозиториях получают
//      один ключ - «схлопнуть» закрыл бы чужую задачу;
//   3. адреса внутри приложения в якоре (#inbox/письмо, #/маршрут, #12345 в
//      Telegram) склеиваются в один - «схлопнуть» закрыл бы другое письмо;
//   4. одна и та же страница на разных портах склеивается;
//   5. обычный якорь страницы (#section) делает адрес другим.
import { ключ, номерТикета, заголовок, ПО_УМОЛЧАНИЮ } from "../lib.js";

const н = { ...ПО_УМОЛЧАНИЮ };
let провалов = 0, всего = 0;
function проверка(имя, ок, подробно = "") {
  всего++;
  if (!ок) провалов++;
  console.log(`${ок ? "ок  " : "ПРОВАЛ"}  ${имя}${ок ? "" : "  " + подробно}`);
}
const один = (а, б) => ключ(а, н) === ключ(б, н);

const т = "https://redmine.test/issues/777";
for (const хвост of ["#note-7", "?tab=history", "/edit", "/relations", ".json"]) {
  проверка(`тикет с хвостом ${хвост} - тот же`, один(т, т + хвост), ключ(т + хвост, н));
}
проверка("ключ тикета Redmine прежний", ключ(т, н) === "redmine.test | тикет 777", ключ(т, н));
проверка("номер тикета читается из ключа", номерТикета(ключ(т, н)) === "777");
проверка("Redmine под подкаталогом - тикет по номеру",
         один("https://h.test/redmine/issues/5", "https://h.test/redmine/issues/5?tab=notes"));
проверка("разные тикеты - разные", !один(т, "https://redmine.test/issues/778"));

проверка("GitHub: один номер в разных репозиториях - разные",
         !один("https://github.com/a/b/issues/5", "https://github.com/c/d/issues/5"),
         ключ("https://github.com/a/b/issues/5", н));
проверка("GitHub: та же задача с якорем - одна",
         один("https://github.com/a/b/issues/5", "https://github.com/a/b/issues/5#issuecomment-1"));
проверка("GitLab: разные проекты - разные",
         !один("https://gitlab.com/g/p/-/issues/9", "https://gitlab.com/g/q/-/issues/9"));
проверка("номер задачи GitHub тоже читается",
         номерТикета(ключ("https://github.com/a/b/issues/5", н)) === "5");

проверка("Gmail: два письма - разные",
         !один("https://mail.google.com/mail/u/0/#inbox/AAA", "https://mail.google.com/mail/u/0/#inbox/BBB"));
проверка("маршрут #/ - разные",
         !один("https://app.test/#/orders", "https://app.test/#/settings"));
проверка("Telegram: два чата - разные",
         !один("https://web.telegram.org/a/#123456", "https://web.telegram.org/a/#654321"));
проверка("обычный якорь страницы не делает адрес другим",
         один("https://docs.test/page", "https://docs.test/page#section-2"));

проверка("разные порты - разные",
         !один("http://localhost:3000/", "http://localhost:8080/"));
проверка("порт по умолчанию не мешает", один("https://example.com:443/x", "https://example.com/x"));
проверка("www не мешает", один("https://www.example.com/x", "https://example.com/x"));
проверка("метки utm не мешают", один("https://example.com/x?utm_source=a", "https://example.com/x"));
проверка("chrome:// не сравниваем", ключ("chrome://newtab/", н) === null);

const г = { ключ: ключ(т, н), список: [{ title: "Задача #777: Платёж завис - Redmine" }] };
проверка("заголовок группы - номер и тема", заголовок(г) === "#777 · Платёж завис", заголовок(г));

console.log(`\n${провалов ? "ПРОВАЛОВ " + провалов + " из " + всего : "все " + всего + " проверок пройдены"}`);
process.exit(провалов ? 1 : 0);
